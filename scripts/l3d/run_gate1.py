#!/usr/bin/env python
"""Gate 1 (check selection, per subset) from the A1, A2, A3 and A4 results; writes gate1.{json,md}.

A loss check passes if (i) it passes the A2 sanity test (observed Yes in every cell
Table 1 marks Yes, both synthetic scenes), (ii) Spearman rho(residual, target) >= 0.3,
(iii) the part it can see is >= 20% of the matching error (source swap: S + SC share of
the depth error, A3; camera swap: non-rigid share of camera-frame error, A1; ray center:
image-plane share of self-frame error, A1) and (iv) its median residual is >= 20% of the
median error (camera checks: of the median Umeyama translation error, A4). The proposal
asks for (iv) on training data; these are the WorldTrack eval clips.

Example:
    .venv/bin/python scripts/l3d/run_gate1.py
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from l3d.report import SUBSETS, fmt, jsonable  # noqa: E402

RES = REPO / "results/l3d"
# loss check -> (A2 column, A3 detection key)
LOSS_CHECKS = {
    "source_swap": ("source_swap", "source_swap"),
    "camera_swap": ("camera_swap_se3", "camera_swap_se3"),
    "ray_center": ("ray_center_se3", "ray_center"),
}
RHO_MIN, SHARE_MIN, RATIO_MIN = 0.3, 0.2, 0.2


def a2_pass(a2: dict[str, Any], column: str) -> tuple[bool, list[str]]:
    misses = []
    for scene, res in a2["results"].items():
        for cell, v in res["cells"].items():
            col = v["columns"].get(column, {})
            if col.get("predicted") == "Yes" and col.get("observed") != "Yes":
                misses.append(f"{scene} {cell}: {col.get('observed')}")
    return not misses, misses


def gate(a1: dict, a2: dict, tsc: dict, det: dict, a4: dict) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for check, (a2_col, det_key) in LOSS_CHECKS.items():
        ok_i, misses = a2_pass(a2, a2_col)
        out[check] = {"a2_pass": ok_i, "a2_misses": misses, "subsets": {}}
        for s in SUBSETS:
            m = det["per_subset"].get(s, {}).get(det_key, {})
            rho = m.get("vs_target", {}).get("residual", {}).get("spearman")
            if check == "source_swap":
                sh = tsc["per_subset"][s]["log_depth"]["shares"]
                visible = sh["S"] + sh["SC"]
                ratio = m["median_residual"] / m["median_error"] if m.get("median_error") else None
            else:
                pose = a4["per_subset"][s]["methods"]["umeyama"]["trans_rel_median"]
                res_med = a4["per_subset"][s]["cs_residual_median" if check == "camera_swap" else "rc_spread_median"]
                ratio = res_med / pose if pose else None
                visible = (a1["per_subset"][s]["camera_nonrigid_share"] if check == "camera_swap"
                           else a1["per_subset"][s]["perp_share"])
            passes = {
                "i": ok_i,
                "ii": rho is not None and rho >= RHO_MIN,
                "iii": visible is not None and visible >= SHARE_MIN,
                "iv": ratio is not None and ratio >= RATIO_MIN,
            }
            out[check]["subsets"][s] = {"rho": rho, "visible": visible, "ratio": ratio, "passes": passes,
                                        "loss": all(passes.values())}
    out["rq1"] = {s: {"disagreement_xyz": tsc["per_subset"][s]["xyz"]["disagreement"],
                      "depth_offset_share": a1["per_subset"][s]["depth_shares"]["offset"]} for s in SUBSETS}
    return out


def write_md(g: dict[str, Any], path: Path, label: str = "OpenD4RT 48CLIP") -> None:
    yn = lambda b: "**pass**" if b else "fail"  # noqa: E731
    lines = [
        f"# Gate 1: check selection ({label}, WorldTrack eval clips, clip [0, 48))",
        "",
        "Generated by `scripts/l3d/run_gate1.py` from `a1_decompose`, `a2_synthetic`, `a3_tsc`, `a3_detection` and",
        "`a4_pose`. A check becomes a loss on a subset only if all four criteria pass:",
        "(i) A2 sanity test; (ii) rho(residual, target) >= 0.3; (iii) visible part >= 20% of the matching error",
        "(source swap: S + SC share of depth error; camera swap: non-rigid share of camera-frame error; ray center:",
        "image-plane share of self-frame error); (iv) median residual >= 20% of the median error (source swap: of",
        "the median relative 3D error of the same rows; camera checks: of the median Umeyama translation error).",
        "Caveat: the proposal asks for (iv) on training data; these are eval clips.",
        "",
        "| Check | Subset | (i) A2 | (ii) rho | (iii) visible share | (iv) median ratio | Loss? |",
        "| --- | --- | --- | ---: | ---: | ---: | --- |",
    ]
    for check in LOSS_CHECKS:
        c = g[check]
        for s, v in c["subsets"].items():
            p = v["passes"]
            lines.append(f"| {check.replace('_', ' ')} | `{s}` | {yn(p['i'])} | {fmt(v['rho'])} ({yn(p['ii'])}) | "
                         f"{fmt(v['visible'])} ({yn(p['iii'])}) | {fmt(v['ratio'], 2)} ({yn(p['iv'])}) | "
                         f"{'**yes**' if v['loss'] else 'no'} |")
    lines += ["", "A2 misses (cells Table 1 marks Yes where the check did not respond):", ""]
    for check in LOSS_CHECKS:
        misses = g[check]["a2_misses"]
        lines.append(f"- {check.replace('_', ' ')}: " + ("none" if not misses else "; ".join(misses)))
    lines += [
        "",
        "## RQ1 headline numbers",
        "",
        "| Subset | Disagreement (1 - T) of 3D error | Depth offset share of depth error |",
        "| --- | ---: | ---: |",
    ]
    for s, v in g["rq1"].items():
        lines.append(f"| `{s}` | {fmt(v['disagreement_xyz'])} | {fmt(v['depth_offset_share'])} |")
    lines += ["", "RQ1 asks whether disagreement is >= 20%; the proposal expects the \"invisible\" story for depth where",
              "the offset share is >= 50%."]
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", type=Path, default=RES)
    ap.add_argument("--model-label", default=None, help="model name in the report")
    ap.add_argument("--out", type=Path, default=RES / "gate1")
    args = ap.parse_args()
    load = lambda p: json.loads((args.results / p).read_text())  # noqa: E731
    g = gate(load("a1_decompose/a1.json"), load("a2_synthetic/sensitivity.json"), load("a3_tsc/a3_tsc.json"),
             load("a3_detection/a3_detection.json"), load("a4_pose/a4_pose.json"))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "gate1.json").write_text(json.dumps(jsonable(g), indent=1))
    write_md(g, args.out / "gate1.md", label=args.model_label or "OpenD4RT 48CLIP")
    print((args.out / "gate1.md").read_text())


if __name__ == "__main__":
    main()
