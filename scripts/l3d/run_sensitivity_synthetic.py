#!/usr/bin/env python
"""A2: run the synthetic sensitivity test and write sensitivity.{json,md,png}.

Example:
    .venv/bin/python scripts/l3d/run_sensitivity_synthetic.py --seeds 5
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path
from typing import Any

import numpy as np

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

from l3d import sensitivity as sens  # noqa: E402

SHORT = {
    "source_swap": "SS model u2",
    "source_swap_gt_u2": "SS GT u2",
    "camera_swap_se3": "CS SE3",
    "camera_swap_sim3": "CS Sim3",
    "ray_center_se3": "RC SE3-fit",
    "ray_center_sim3": "RC Sim3-fit",
    "ray_center_gt": "RC GT K,R,t",
    "reprojection": "Reproj",
    "static_rigidity": "SR incl t_t=c",
    "static_rigidity_excl_tc": "SR excl t_t=c",
}
KIND_LABEL = {
    "depth_offset": "depth offset",
    "depth_jitter": "depth jitter",
    "image_plane": "image-plane",
    "nonrigid": "non-rigid cam.",
    "nonrigid_radial": "non-rigid along ray",
    "gauge": "rigid gauge",
    "scale": "per-camera scale",
}


def _jsonable(x: Any) -> Any:
    if isinstance(x, dict):
        return {str(k): _jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_jsonable(v) for v in x]
    if isinstance(x, np.ndarray):
        return _jsonable(x.tolist())
    if isinstance(x, (np.floating, float)):
        return None if not np.isfinite(x) else float(x)
    if isinstance(x, (np.integer,)):
        return int(x)
    if isinstance(x, np.bool_):
        return bool(x)
    return x


def _is_table_row(kind: str, dep: str) -> bool:
    return (kind, dep) in sens.TABLE1 or (kind, dep) in sens.DERIVED


def _cell_text(v: dict[str, Any]) -> str:
    pred = v["predicted"] if v["predicted"] is not None else "-"
    mean = 0.0 if abs(v["mean"]) < 5e-4 else v["mean"]
    txt = f"{v['observed']} {mean:.3f}±{v['std']:.3f} [{pred}]"
    return f"**{txt}**" if v["agree"] is False else txt


def _matrix_md(result: dict[str, Any], rows: list[str]) -> list[str]:
    cols = list(sens.COLUMNS)
    lines = ["| error | dep | " + " | ".join(SHORT[c] for c in cols) + " |",
             "| --- | --- | " + " | ".join("---" for _ in cols) + " |"]
    for key in rows:
        cell = result["cells"][key]
        tag = " (derived)" if (cell["kind"], cell["dep"]) in sens.DERIVED else ""
        lines.append(f"| {KIND_LABEL[cell['kind']]}{tag} | {cell['dep']} | "
                     + " | ".join(_cell_text(cell["columns"][c]) for c in cols) + " |")
    return lines


def _row_order(result: dict[str, Any]) -> tuple[list[str], list[str]]:
    table_order = [f"{k}/{d}" for (k, d) in list(sens.TABLE1) + list(sens.DERIVED)]
    table_rows = [k for k in table_order if k in result["cells"]]
    other = [k for k in result["cells"] if k not in table_rows]
    return table_rows, other


def write_md(results: dict[str, dict[str, Any]], path: Path, argv: list[str], runtime_s: float) -> None:
    main = results["translating"]
    cfg = main["config"]
    th = cfg["thresholds"]
    lines = [
        "# A2: sensitivity of the five checks on a synthetic scene",
        "",
        f"Generated by `scripts/l3d/run_sensitivity_synthetic.py {' '.join(argv)}` in {runtime_s:.0f} s "
        "(code: `l3d/sensitivity.py`, all numbers in `sensitivity.json`).",
        "",
        f"- Response = (residual_injected - residual_clean) / eps, eps = {cfg['eps']}, mean ± std over "
        f"{len(cfg['seeds'])} seeds (new scene, draws and queries per seed). "
        f"Class: Yes >= {th['yes']}, Partly >= {th['partly']}, No below. `[x]` = Table 1 prediction "
        "with footnotes resolved, `[-]` = no prediction, **bold** = disagreement.",
        f"- Virtual 2D head follows the 3D output (`uv_follows_xyz={cfg['uv_follows_xyz']}`), so 'SS model u2' tests "
        "footnote a; 'SS GT u2' is the GT-u2 control (identical to running with a perfect 2D head).",
        "- Ray-center columns take the max of the two scores (per-ray spread / mean depth, center distance to t* / "
        "median depth); per-score responses are in the JSON. 'RC GT K,R,t' is not label-free and has no Table 1 entry.",
        "- Clean decoder: max |residual| over all checks and seeds = "
        f"{max(v['max_abs'] for k, v in main['clean_residuals'].items() if k not in ('reprojection_px', 'u2_px_err')):.1e}.",
    ]
    for name, res in results.items():
        st = res["scene_stats"]
        lines.append(
            f"- Scene `{name}`: {st['n_points']:.0f} points ({st['n_static']:.0f} static), depth "
            f"{st['depth_min']:.1f}-{st['depth_max']:.1f} m (median {st['depth_median']:.1f}), camera path "
            f"{st['camera_path_length_m']:.2f} m, rotation {st['camera_rotation_deg']:.1f} deg, static-rigidity "
            f"baseline/depth {st['baseline_over_depth']:.3f}."
        )
    table_rows, other_rows = _row_order(main)
    lines += ["", "## Table 1 rows, translating camera", ""] + _matrix_md(main, table_rows)
    lines += ["", "## Cells without a Table 1 entry (translating camera, observed only)", ""] + _matrix_md(main, other_rows)
    if "rotation_only" in results:
        rot = results["rotation_only"]
        rows, _ = _row_order(rot)
        lines += ["", "## Table 1 rows, rotation-only camera (footnote b)", ""] + _matrix_md(rot, rows)

    lines += ["", "## Disagreements with Table 1", ""]
    for name, res in results.items():
        dis = res["disagreements"]
        lines.append(f"### Scene `{name}`: {len(dis)} disagreement(s)")
        lines.append("")
        for d in dis:
            src = "derived from Table 1" if d["source"] == "derived" else f"Table 1: '{d['table_entry']}'"
            lines.append(
                f"- `{d['cell']}` / {SHORT[d['column']]}: observed **{d['observed']}** ({d['mean']:.3f} ± {d['std']:.3f}), "
                f"predicted {d['predicted']} ({src}). {d['explanation']}"
            )
        lines.append("")
    path.write_text("\n".join(lines) + "\n")


def write_png(results: dict[str, dict[str, Any]], path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LinearSegmentedColormap, LogNorm
    from matplotlib.patches import Rectangle

    ramp = ["#cde2fb", "#9ec5f4", "#6da7ec", "#3987e5", "#256abf", "#184f95", "#0d366b"]
    cmap = LinearSegmentedColormap.from_list("blue_seq", ramp)
    norm = LogNorm(vmin=1e-3, vmax=2.0)
    ink, muted = "#1f1f1e", "#6b6a66"
    cols = list(sens.COLUMNS)
    names = list(results)
    main = results["translating"]
    table_rows, other_rows = _row_order(main)
    rows = table_rows + other_rows
    fig, axes = plt.subplots(1, len(names), figsize=(10.5 * len(names), 0.42 * len(rows) + 2.6), squeeze=False)
    for ax, name in zip(axes[0], names):
        res = results[name]
        vals = np.array([[res["cells"][r]["columns"][c]["mean"] for c in cols] for r in rows])
        ax.imshow(np.clip(vals, 1e-3, 2.0), cmap=cmap, norm=norm, aspect="auto")
        for i, r in enumerate(rows):
            for j, c in enumerate(cols):
                v = res["cells"][r]["columns"][c]
                pred = v["predicted"]
                txt = f"{v['observed'][0]} {v['mean']:.2f}" if v["mean"] >= 0.005 else f"{v['observed'][0]} 0"
                if pred is not None:
                    txt += f"\n[{pred[0]}]"
                dark = np.clip(v["mean"], 1e-3, 2.0) > 0.12
                ax.text(j, i, txt, ha="center", va="center", fontsize=7,
                        color="white" if dark else ink, fontweight="bold" if v["agree"] is False else "normal")
                if v["agree"] is False:
                    ax.add_patch(Rectangle((j - 0.47, i - 0.45), 0.94, 0.9, fill=False, lw=2.2, ec="#f28c28"))
        ax.axhline(len(table_rows) - 0.5, color=ink, lw=1.0)
        ax.set_xticks(range(len(cols)))
        ax.set_xticklabels([SHORT[c] for c in cols], rotation=35, ha="right", fontsize=8, color=ink)
        ax.set_yticks(range(len(rows)))
        ax.set_yticklabels([f"{KIND_LABEL[r.split('/')[0]]} / {r.split('/')[1]}" for r in rows], fontsize=8, color=ink)
        ax.tick_params(length=0)
        for sp in ax.spines.values():
            sp.set_visible(False)
        ax.set_title(f"{name.replace('_', ' ')} camera: response / eps (letter = observed, [letter] = Table 1)",
                     fontsize=9, color=ink, loc="left")
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    cb = fig.colorbar(sm, ax=axes[0].tolist(), fraction=0.015, pad=0.01)
    cb.set_ticks([1e-3, 1e-2, 1e-1, 1.0])
    cb.set_ticklabels(["<=0.001", "0.01 (Partly)", "0.1 (Yes)", "1"])
    cb.ax.tick_params(labelsize=8, colors=muted)
    cb.outline.set_visible(False)
    fig.text(0.01, 0.005, "Rows above the line: Table 1 rows (+ derived along-ray control). Orange box = observed "
             "class differs from Table 1. Y/P/N = Yes (>=0.1) / Partly (>=0.01) / No.", fontsize=8, color=muted)
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(fig)


def print_summary(results: dict[str, dict[str, Any]]) -> None:
    cols = list(sens.COLUMNS)
    for name, res in results.items():
        print(f"\n=== scene: {name} ===")
        print(f"{'cell':22s} " + " ".join(f"{SHORT[c][:12]:>13s}" for c in cols))
        table_rows, other = _row_order(res)
        for key in table_rows + other:
            cell = res["cells"][key]
            parts = []
            for c in cols:
                v = cell["columns"][c]
                pred = v["predicted"][0] if v["predicted"] else "-"
                flag = "!" if v["agree"] is False else " "
                parts.append(f"{v['observed'][0]}{flag}{pred} {v['mean']:7.3f}")
            print(f"{key:22s} " + " ".join(f"{p:>13s}" for p in parts))
        print(f"-- {len(res['disagreements'])} disagreement(s):")
        for d in res["disagreements"]:
            print(f"  {d['cell']:22s} {d['column']:24s} observed {d['observed']:6s} ({d['mean']:.3f}) "
                  f"predicted {d['predicted']}: {d['explanation']}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--eps", type=float, default=0.05)
    ap.add_argument("--yes", type=float, default=0.1, help="response threshold for Yes")
    ap.add_argument("--partly", type=float, default=0.01, help="response threshold for Partly")
    ap.add_argument("--no-uv-follows-xyz", action="store_true", help="virtual 2D head returns GT pixels")
    ap.add_argument("--no-rotation-only", action="store_true", help="skip the rotation-only camera scene")
    ap.add_argument("--T", type=int, default=24)
    ap.add_argument("--occlusion-prob", type=float, default=0.0)
    ap.add_argument("--out", type=Path, default=REPO / "results/l3d/a2_synthetic")
    args = ap.parse_args()

    t0 = time.time()
    common = dict(
        seeds=tuple(range(args.seeds)), eps=args.eps, uv_follows_xyz=not args.no_uv_follows_xyz,
        yes=args.yes, partly=args.partly, scene_kwargs={"T": args.T, "occlusion_prob": args.occlusion_prob},
    )
    results = {"translating": sens.run_sensitivity(camera_translates=True, **common)}
    if not args.no_rotation_only:
        results["rotation_only"] = sens.run_sensitivity(camera_translates=False, **common)
    for res in results.values():
        dis = sens.disagreements(res)
        for d in dis:
            d["explanation"] = sens.explain(d, res)
        res["disagreements"] = dis
    runtime = time.time() - t0

    args.out.mkdir(parents=True, exist_ok=True)
    payload = {"table1": {f"{k}/{d}": v for (k, d), v in sens.TABLE1.items()},
               "derived": {f"{k}/{d}": v for (k, d), v in sens.DERIVED.items()},
               "columns": sens.COLUMN_LABELS, "runtime_s": runtime, "results": results}
    (args.out / "sensitivity.json").write_text(json.dumps(_jsonable(payload), indent=1))
    write_md(results, args.out / "sensitivity.md", sys.argv[1:], runtime)
    write_png(results, args.out / "sensitivity.png")
    print_summary(results)
    print(f"\nwrote {args.out}/sensitivity.{{json,md,png}} in {runtime:.1f} s")


if __name__ == "__main__":
    main()
